def seed_courses(apps, schema_editor):
    Course = apps.get_model("courses", "Course")
    seed_dir = Path(__file__).resolve().parent.parent / "seed_images"
    for item in COURSES:
        if Course.objects.filter(slug=item["slug"]).exists():
            continue
        course = Course(
            title=item["title"],
            slug=item["slug"],
            short_description=item["short_description"],
            description=item["description"],
            price=item["price"],
            is_published=True,
            delivery_email_body=item["delivery_email_body"],
        )
        image_path = seed_dir / item["image"]
        if image_path.is_file():
            course.cover.save(
                item["image"],
                ContentFile(image_path.read_bytes()),
                save=False,
            )
        course.save()


def unseed_courses(apps, schema_editor):
    Course = apps.get_model("courses", "Course")
    Course.objects.filter(slug__in=[item["slug"] for item in COURSES]).delete()


